#define DECOR_TITLEBAR_HEIGHT 28
#define DECOR_BUTTON_RADIUS 7

static int decor_last_cx[3] = {16, 40, 64};
static int decor_last_cy = 14;
static int decor_last_r = 7;
static int decor_last_titlebar_h = 28;

static void decor_px(Surface *s, int x, int y, uint32_t color) {
    if (!s || !s->pixels) return;
    if (x < 0 || y < 0 || x >= s->width || y >= s->height) return;
    int stride = s->stride > 0 ? s->stride : s->width;
    if (stride <= 0) stride = s->width;
    s->pixels[y * stride + x] = color;
}

static void decor_fill_rect(Surface *s, int x, int y, int w, int h, uint32_t color) {
    for (int yy = 0; yy < h; ++yy)
        for (int xx = 0; xx < w; ++xx)
            decor_px(s, x + xx, y + yy, color);
}

static void decor_fill_circle(Surface *s, int cx, int cy, int r, uint32_t color) {
    for (int y = -r; y <= r; ++y)
        for (int x = -r; x <= r; ++x)
            if (x * x + y * y <= r * r)
                decor_px(s, cx + x, cy + y, color);
}

static int decor_text_width(const char *text, int scale) {
    if (!text) return 0;
    return (int)strlen(text) * 8 * scale;
}

static void decor_draw_text(Surface *s, int x, int y, const char *text, uint32_t color, int scale) {
    if (!s || !text) return;
    int cx = x;
    for (size_t i = 0; text[i]; ++i) {
        unsigned char ch = (unsigned char)text[i];
        if (ch == '\n') { cx = x; y += 8 * scale; continue; }
        if (ch > 127) ch = '?';
        for (int row = 0; row < 8; ++row) {
            unsigned char bits = decor_font8x8[ch][row];
            for (int col = 0; col < 8; ++col) {
                if (bits & (1 << (7 - col))) {
                    for (int sy = 0; sy < scale; ++sy)
                        for (int sx = 0; sx < scale; ++sx)
                            decor_px(s, cx + col * scale + sx, y + row * scale + sy, color);
                }
            }
        }
        cx += 8 * scale;
    }
}

static void decor_draw_one(Surface *s, const char *title) {
    if (!s) return;
    int w = s->width;
    int tb = DECOR_TITLEBAR_HEIGHT;
    if (tb > s->height) tb = s->height;
    if (tb < 8) tb = 8;

    uint32_t bar = 0x00F2F2F7u;
    decor_fill_rect(s, 0, 0, w, tb, bar);
    decor_fill_rect(s, 0, tb - 1, w, 1, 0x00C6C6C8u);

    int r = DECOR_BUTTON_RADIUS;
    int cy = tb / 2;
    int spacing = 24;
    int start_x = 16;
    int centers[3] = { start_x, start_x + spacing, start_x + spacing * 2 };
    uint32_t colors[3] = { 0x00FF5F57u, 0x00FFBD2Eu, 0x0027C93Fu };
    for (int i = 0; i < 3; ++i)
        decor_fill_circle(s, centers[i], cy, r, colors[i]);

    decor_last_titlebar_h = tb;
    decor_last_cy = cy;
    decor_last_r = r;
    for (int i = 0; i < 3; ++i) decor_last_cx[i] = centers[i];

    if (title) {
        int scale = 1;
        int tw = decor_text_width(title, scale);
        int tx = (w - tw) / 2;
        int ty = (tb - 8 * scale) / 2;
        int left_limit = centers[2] + r + 8;
        if (tx < left_limit) tx = left_limit;
        if (tx + tw > w - 8) tx = w - 8 - tw;
        if (tx < left_limit) tx = left_limit;
        decor_draw_text(s, tx, ty, title, 0x003C3C43u, scale);
    }
}

void decor_draw(Surface *window_surface, const char *title) {
    decor_draw_one(window_surface, title);
}

void decor_draw_titlebar(Surface *window_surface, const char *title) {
    decor_draw_one(window_surface, title);
}

static int decor_hit(int x, int y) {
    if (y < 0 || y >= decor_last_titlebar_h) return DECOR_BTN_NONE;
    for (int i = 0; i < 3; ++i) {
        int dx = x - decor_last_cx[i];
        int dy = y - decor_last_cy;
        if (dx * dx + dy * dy <= (decor_last_r + 2) * (decor_last_r + 2))
            return i + 1;
    }
    return DECOR_BTN_NONE;
}

int decor_hit_test(int x, int y) {
    return decor_hit(x, y);
}

int decor_hit_test_xy(int x, int y) {
    return decor_hit(x, y);
}

int decor_hit_test_surface(Surface *window_surface, int x, int y) {
    (void)window_surface;
    return decor_hit(x, y);
}

