static int taskbar_ready = 0;

static char *taskbar_strdup(const char *s) {
    if (!s) return 0;
    size_t n = strlen(s);
    char *d = (char *)malloc(n + 1);
    if (!d) return 0;
    memcpy(d, s, n + 1);
    return d;
}

static void taskbar_put_pixel(Surface *surface, int x, int y, uint32_t color) {
    if (!surface || !surface->pixels) return;
    int w = surface->width > 0 ? surface->width : surface->w;
    int h = surface->height > 0 ? surface->height : surface->h;
    int stride = surface->stride > 0 ? surface->stride : (w > 0 ? w : 0);
    if (stride <= 0) stride = w;
    if (x < 0 || y < 0 || x >= w || y >= h) return;
    surface->pixels[y * stride + x] = color;
}

static void taskbar_fill_rect(Surface *surface, int x, int y, int w, int h, uint32_t color) {
    if (!surface || w <= 0 || h <= 0) return;
    for (int yy = 0; yy < h; ++yy)
        for (int xx = 0; xx < w; ++xx)
            taskbar_put_pixel(surface, x + xx, y + yy, color);
}

