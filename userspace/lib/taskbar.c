static void taskbar_draw_text(Surface *surface, int x, int y, const char *text, uint32_t color) {
    if (!surface || !text) return;
    int cx = x;
    for (size_t i = 0; text[i]; ++i) {
        unsigned char ch = (unsigned char)text[i];
        if (ch == '\n') { cx = x; y += 8; continue; }
        if (ch < 32 || ch > 127) { cx += 8; continue; }
        const unsigned char *glyph = taskbar_font8x8[ch - 32];
        for (int row = 0; row < 8; ++row) {
            unsigned char bits = glyph[row];
            for (int col = 0; col < 8; ++col) {
                if (bits & (1 << (7 - col)))
                    taskbar_put_pixel(surface, cx + col, y + row, color);
            }
        }
        cx += 8;
    }
}

void taskbar_init(void) {
    for (int i = 0; i < taskbar_app_count; ++i) {
        if (taskbar_apps[i]) free(taskbar_apps[i]);
        taskbar_apps[i] = 0;
    }
    taskbar_app_count = 0;
    taskbar_clock_ms = time_ms();
    taskbar_ready = 1;
}

void taskbar_add_app(const char *name) {
    if (taskbar_app_count >= TASKBAR_MAX_APPS) return;
    char *d = taskbar_strdup(name);
    if (!d && name) d = (char *)name;
    taskbar_apps[taskbar_app_count++] = d;
}

void taskbar_clock_update(unsigned long time_ms) {
    taskbar_clock_ms = time_ms;
}

static uint32_t taskbar_app_color(const char *name) {
    unsigned int h = 0;
    if (name) for (const char *p = name; *p; ++p) h = h * 31 + (unsigned char)*p;
    uint32_t colors[] = {0xFF4A90D9u, 0xFF50C878u, 0xFFFF8C42u, 0xFFB36AE2u, 0xFFE85D75u, 0xFF3ACFCFu};
    return colors[h % (sizeof(colors)/sizeof(colors[0]))];
}

void taskbar_draw(Surface *surface) {
    if (!surface) return;
    int w = surface->width > 0 ? surface->width : surface->w;
    int h = surface->height > 0 ? surface->height : surface->h;
    if (w <= 0 || h <= 0) return;

    int bar_h = TASKBAR_HEIGHT;
    if (bar_h > h) bar_h = h;
    int bar_y = h - bar_h;

    const ThemeEffects *fx = &theme_default()->effects;
    int stride = surface->stride > 0 ? surface->stride : w;
    GfxCanvas canvas = { surface->pixels, w, h, stride, 0 };
    GfxGlass glass = { fx->glass_blur_radius, 0, fx->glass_tint, fx->glass_tint_alpha,
                       fx->glass_highlight, fx->glass_highlight_alpha };
    if (gfx_glass_apply(&canvas, 0, bar_y, w, bar_h, &glass) != 0) {
        /* No scratch memory for the blur: fall back to the flat tint. */
        taskbar_fill_rect(surface, 0, bar_y, w, bar_h, fx->glass_tint);
    }

    /* App icons */
    int x = 8;
    int icon_size = bar_h - 8;
    if (icon_size < 16) icon_size = 16;
    for (int i = 0; i < taskbar_app_count; ++i) {
        if (x + icon_size + 4 > w) break;
        const char *name = taskbar_apps[i] ? taskbar_apps[i] : "App";
        uint32_t col = taskbar_app_color(name);
        gfx_fill_round_rect(&canvas, x, bar_y + 4, icon_size, icon_size, fx->button_radius, col, 255);
        gfx_stroke_round_rect(&canvas, x, bar_y + 4, icon_size, icon_size, fx->button_radius,
                              fx->glass_highlight, fx->glass_highlight_alpha);
        /* first letter */
        char letter[2];
        letter[0] = name[0] ? name[0] : '?';
        letter[1] = '\0';
        int tx = x + (icon_size - 8) / 2;
        int ty = bar_y + 4 + (icon_size - 8) / 2;
        taskbar_draw_text(surface, tx, ty, letter, 0xFFFFFFFFu);
        /* name below? draw to right if space */
        x += icon_size + 6;
    }

    /* Clock on right */
    char buf[64];
    snprintf(buf, sizeof(buf), "%lu ms", taskbar_clock_ms);
    int text_w = (int)strlen(buf) * 8;
    int cx = w - text_w - 12;
    if (cx < 0) cx = 0;
    int cy = bar_y + (bar_h - 8) / 2;
    gfx_fill_round_rect(&canvas, cx - 6, bar_y + 6, text_w + 12, bar_h - 12, (bar_h - 12) / 2,
                        fx->glass_highlight, fx->glass_highlight_alpha / 2);
    taskbar_draw_text(surface, cx, cy, buf, 0xFFE0E0E0u);
}
